#!/usr/bin/env python3
"""Generate the fine-tuning corpus for direction D: the ternary target's own responses.

    ~/.venv-dspark/bin/python bench/drafter/gen_data.py <out.jsonl> [--n 300] [--seed 7]

The DFlash paper trains on responses generated by the target model, and that is the whole
point here: the stock DFlash2 drafter was trained on full-precision Qwen3.8-27B responses,
and what it has to learn is how the ternary target's hidden states and continuations differ.
Prompts come from CodeAlpaca-20k, one of the paper's own sources. Generation runs in-process
through mlx-dspark's dflash loop with the stock drafter, so the record carries the exact
token ids the target committed (the target verifies every token, so these are its own
samples at the served settings: temperature 1.0, top-p 0.95, top-k 20).

Each line: {"prompt_ids": [...], "response_ids": [...], "thinking": bool, "finish": str,
            "prompt": str, "split": "train"|"eval", "temperature": float,
            "round_lengths": [...]}. Written as each response completes. With --temperature 0 the
response is the target's argmax path, and the round lengths are where the served loop drew its
anchors, which is what a served-anchored proxy and on-policy training need.
"""
import argparse
import json
import os
import random
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
import patches

patches.install_all()

import mlx.core as mx
from huggingface_hub import hf_hub_download
from mlx_dspark.generate import dflash_generate
from mlx_dspark.load import load_dflash, load_target

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--n", type=int, default=300)
ap.add_argument("--eval", type=int, default=40)
ap.add_argument("--seed", type=int, default=7)
ap.add_argument("--prompts-json", help="local instruction/input JSON array, used in file order; "
                                       "optional thinking and category")
ap.add_argument("--target", default="prism-ml/Ternary-Bonsai-2-27B-mlx-2bit")
ap.add_argument("--drafter", default="z-lab/Qwen3.8-27B-DFlash2")
ap.add_argument("--temperature", type=float, default=1.0,
                help="0 = greedy: the corpus is then the target's argmax path and the loop's "
                     "round lengths locate the anchors it drew")
args = ap.parse_args()

if args.n <= 0 or not 0 <= args.eval <= args.n:
    ap.error("require n > 0 and 0 <= eval <= n")
source = args.prompts_json or hf_hub_download("sahil2801/CodeAlpaca-20k", "code_alpaca_20k.json",
                                              repo_type="dataset")
with open(source) as f:
    src = json.load(f)
rng = random.Random(args.seed)
if len(src) < args.n:
    ap.error("prompt source has fewer than n rows")
rows = src[:args.n] if args.prompts_json else rng.sample(src, args.n)
prompts = []
for r in rows:
    inp = (r.get("input") or "").strip()
    p = r["instruction"].strip()
    if inp and inp.lower() not in ("<noinput>", "< noinput >", "noinput", ""):
        p = p + "\n\n" + inp
    prompts.append(p)

done: set[str] = set()
if os.path.exists(args.out):
    with open(args.out) as f:
        for line in f:
            try:
                done.add(json.loads(line)["prompt"])
            except (ValueError, KeyError):
                # a half-written last line from an interrupted run; the prompt is redone
                continue
print(f"{len(prompts)} prompts, {len(done)} already done", flush=True)

target, tok = load_target(args.target, require_tap=True, kv_bits=8)
drafter, cfg = load_dflash(args.drafter)
drafter.bind(target.model)
print(f"loaded; block {cfg.block_size}, taps {cfg.target_layer_ids}", flush=True)


def prompt_ids(text: str, thinking: bool) -> list[int]:
    kw = {} if thinking else {"enable_thinking": False}
    out = tok.apply_chat_template([{"role": "user", "content": text}], add_generation_prompt=True,
                                  tokenize=True, **kw)
    if isinstance(out, str):
        out = tok.encode(out)
    return [int(t) for t in out]


t_all = time.time()
n_tok = 0
with open(args.out, "a") as f:
    for i, p in enumerate(prompts):
        if p in done:
            continue
        thinking = rows[i].get("thinking", (i % 3) != 2)
        split = "eval" if i >= args.n - args.eval else "train"
        ids = prompt_ids(p, thinking)
        t0 = time.time()
        res = dflash_generate(target, tok, drafter, prompt_ids=ids, apply_chat_template=False,
                              max_new_tokens=1024 if thinking else 400, max_draft_tokens=7,
                              temperature=args.temperature, top_p=0.95, top_k=20,
                              seed=args.seed + i)
        dt = time.time() - t0
        n_tok += res.num_tokens
        acc = sum(res.accept_lengths) / max(1, len(res.accept_lengths))
        f.write(json.dumps({"prompt_ids": ids, "response_ids": [int(t) for t in res.token_ids],
                            "thinking": thinking, "finish": res.finish_reason, "prompt": p,
                             "split": split, "temperature": args.temperature,
                             "category": rows[i].get("category", "code"),
                            # committed tokens per served round: cumulative sums locate the anchors
                            "round_lengths": [int(a) for a in res.accept_lengths]}) + "\n")
        f.flush()
        print(f"[{i+1}/{len(prompts)}] {split} think={int(thinking)} {res.num_tokens} tok "
              f"in {dt:.0f}s "
              f"({res.num_tokens/dt:.1f} tok/s, {acc:.2f}/round) finish={res.finish_reason}  "
              f"total {n_tok} tok, {(time.time()-t_all)/60:.0f} min", flush=True)
        mx.clear_cache()
print("GEN DONE", flush=True)
